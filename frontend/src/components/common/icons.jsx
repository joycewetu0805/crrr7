/**
 * Icones SVG minimalistes, dessinees a la main pour eviter une dependance
 * supplementaire (une lib d'icones complete est inutile pour ~6 icones).
 * Toutes acceptent className/size comme des composants React classiques.
 */

function base(children, { size = 18, className = '', ...props }) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      aria-hidden="true"
      {...props}
    >
      {children}
    </svg>
  )
}

